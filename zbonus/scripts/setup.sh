#!/bin/bash
set -euo pipefail

CLUSTER_NAME="iot"
KUBE_CONTEXT="k3d-iot"
CONFS_DIR="$(cd "$(dirname "$0")/../confs" && pwd)"

if ! docker info >/dev/null 2>&1; then
    echo "Docker not accessibble, run the installation script (install.sh)"
    exit 1
fi


if ! (k3d cluster list "$CLUSTER_NAME" --no-headers 2>&1); then
    k3d cluster create "$CLUSTER_NAME" --servers 1 --agents 2 --port "8888:8888@loadbalancer"
fi

kube() {
    kubectl --context "$KUBE_CONTEXT" "$@"
}

kube create namespace gitlab 
kube create namespace dev
kube create namespace argocd


kube apply -f "$CONFS_DIR/gitlab.yaml"
kube -n gitlab rollout status deployment/gitlab --timeout=10m

# añadir 127.0.0.1 gitlab.iot.test en hosts
# sacar contraseña root
# usar la contraseña root para acceder a GitLab
# crear usuario y proyecto iot-lab con su repo
# crear token de acceso del usuario iot-lab para Argo CD


#-------------------------------------------------------------------------------

REPO="http://gitlab.iot.test:8081/root/iot-malde-ch.git"
TMP=/tmp/iot-malde-ch


# 1. Reach GitLab: hosts entry + port-forward in the background
grep -q gitlab.iot.test /etc/hosts || echo "127.0.0.1 gitlab.iot.test" | sudo tee -a /etc/hosts
kube -n gitlab port-forward svc/gitlab 8081:8081 >/dev/null 2>&1 &


until curl -fs -o /dev/null http://gitlab.iot.test:8081/users/sign_in; do sleep 2; done

# 2. Root password generated by GitLab (file deleted 24h after the first start)
PASSWORD=$(kube -n gitlab exec deployment/gitlab -- awk '/^Password:/ {print $2}' /etc/gitlab/initial_root_password)
AUTH_REPO="http://root:$(jq -rn --arg p "$PASSWORD" '$p|@uri')@${REPO#http://}"

# 3. Push the manifests. The first push creates the private project ("push to create").
rm -rf "$TMP"
git clone -q "$AUTH_REPO" "$TMP" 2>/dev/null || git init -q -b main "$TMP"
cd ../
cp -R iot-malde-ch/manifests "$TMP/"
git -C "$TMP" add manifests
git -C "$TMP" -c user.name=root -c user.email=root@iot.test \
    commit -qm "feat(manifests): deploy hello world" || echo "Nothing new to commit"
git -C "$TMP" push -q "$AUTH_REPO" HEAD:main
rm -rf "$TMP"


#-------------------------------------------------------------------------------


# Recharge le nouvel import DNS sans attendre la propagation du volume.
kube -n kube-system rollout restart deployment/coredns
kube -n kube-system rollout status deployment/coredns --timeout=4m


argo_server="$(kube -n argocd get deployment argocd-server --ignore-not-found -o name)"
if [[ -z "$argo_server" ]]; then
    kube -n argocd apply --server-side --force-conflicts \
        -f https://raw.githubusercontent.com/argoproj/argo-cd/stable/manifests/install.yaml
fi

kube -n argocd wait deployment --all --for=condition=Available --timeout=600s
kube -n argocd rollout status statefulset/argocd-application-controller --timeout=600s

# 4. Give Argo CD access to the private repository
kube -n argocd create secret generic repo-iot-malde-ch \
    --from-literal=type=git \
    --from-literal=url="$REPO" \
    --from-literal=username=root \
    --from-literal=password="$PASSWORD" \
    --dry-run=client -o yaml | kube apply -f -

kube -n argocd label secret repo-iot-malde-ch argocd.argoproj.io/secret-type=repository --overwrite

kube apply -f "$CONFS_DIR/application.yaml"

kube -n argocd wait application/playground --for=jsonpath='{.status.sync.status}'=Synced --timeout=300s

exec kubectl --context k3d-iot -n argocd port-forward svc/argocd-server 8080:443 &


echo "GitLab : lancez scripts/gitlab.sh, puis publiez le depot avant d'appliquer application.yaml."
echo "Argo CD : lancez scripts/argocd.sh."